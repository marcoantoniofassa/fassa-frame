// Generates the bundled icon registry from design-system/assets/icons (Lucide 0.460.0, ISC). `--check` fails when it is stale.
import { readFile, readdir, writeFile } from 'node:fs/promises';

const check = process.argv.includes('--check');
const iconDir = new URL('../assets/icons/', import.meta.url);
const destination = new URL('../components/core/icon-data.ts', import.meta.url);

const names = (await readdir(iconDir)).filter(name => name.endsWith('.svg')).sort();
const icons = [];
for (const name of names) {
  const svg = await readFile(new URL(name, iconDir), 'utf8');
  const inner = svg.replace(/<metadata>[\s\S]*?<\/metadata>/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (!inner) throw new Error(`Icon without SVG body: ${name}`);
  const body = inner.replace(/\s+/g, ' ').replace(/>\s+</g, '><').replace(/<(\w+)([^>]*?)\s*><\/\1>/g, '<$1$2/>').replace(/\s*\/>/g, '/>').trim();
  // The registry is injected as markup, so reject anything that could execute or load content.
  if (/<script|\son\w+=|href=/i.test(body)) throw new Error(`Unsafe icon markup: ${name}`);
  icons.push(`  '${name.slice(0, -4)}': '${body}',`);
}
const contents = [
  '// Generated by npm run icons from design-system/assets/icons (Lucide, ISC). Do not edit.',
  'export const ICONS: Record<string, string> = {',
  ...icons,
  '};',
  '',
].join('\n');

if (check) {
  const current = await readFile(destination, 'utf8').catch(() => null);
  if (current !== contents) throw new Error('design-system/components/core/icon-data.ts is outdated: run npm run icons.');
} else {
  await writeFile(destination, contents);
}
console.log(`${names.length} icons ${check ? 'verified' : 'generated'}.`);
